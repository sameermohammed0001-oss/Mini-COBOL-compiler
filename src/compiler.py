import re
import sys
from pathlib import Path


class MiniCobolCompiler:
    def __init__(self):
        self.symbol_table = {}
        self.python_code = []
        self.divisions = set()
        self.current_section = None
        self.stopped = False

    def error(self, line_number, message):
        raise ValueError(f"Line {line_number}: {message}")

    def validate_variable(self, name, line_number):
        name = name.upper()

        if name not in self.symbol_table:
            self.error(line_number, f"Undeclared variable '{name}'")

        return name

    def validate_numeric_variables(self, names, line_number, operation):
        for name in names:
            self.validate_variable(name, line_number)

            if self.symbol_table[name]["type"] != "9":
                self.error(
                    line_number,
                    f"{operation} supports numeric variables only"
                )

    def compile(self, input_path, output_path):
        source = Path(input_path)

        if not source.is_file():
            raise FileNotFoundError(
                f"Input file not found: {source}"
            )

        lines = source.read_text(
            encoding="utf-8"
        ).splitlines()

        self.symbol_table = {}
        self.python_code = [
            "# Generated by Mini-COBOL Compiler",
            ""
        ]
        self.divisions = set()
        self.current_section = None
        self.stopped = False

        for line_number, raw_line in enumerate(lines, start=1):
            line = (
                raw_line.strip().upper()
                if '"' not in raw_line
                else raw_line.strip()
            )

            if not line:
                continue

            upper_line = line.upper()

            # Division headers
            if upper_line.startswith("IDENTIFICATION DIVISION."):
                self.divisions.add("IDENTIFICATION")
                self.current_section = "IDENTIFICATION"
                continue

            if upper_line.startswith("ENVIRONMENT DIVISION."):
                self.divisions.add("ENVIRONMENT")
                self.current_section = "ENVIRONMENT"
                continue

            if upper_line.startswith("DATA DIVISION."):
                self.divisions.add("DATA")
                self.current_section = "DATA"
                continue

            if upper_line.startswith("PROCEDURE DIVISION."):
                self.divisions.add("PROCEDURE")
                self.current_section = "PROCEDURE"
                continue

            # Program identification
            if re.fullmatch(
                r"PROGRAM-ID\.\s+[A-Z0-9-]+\.",
                upper_line
            ):
                continue

            # Working storage section
            if upper_line == "WORKING-STORAGE SECTION.":
                self.current_section = "WORKING-STORAGE"
                continue

            # Stop execution
            if upper_line == "STOP RUN.":
                self.stopped = True
                break

            # Ignore identification division contents
            if self.current_section == "IDENTIFICATION":
                continue

            # Variable declarations
            if self.current_section in (
                "ENVIRONMENT",
                "DATA",
                "WORKING-STORAGE"
            ):
                if self.current_section == "ENVIRONMENT":
                    continue

                declaration = re.fullmatch(
                    r"01\s+([A-Z][A-Z0-9-]*)\s+PIC\s+([9X])\((\d+)\)\.",
                    upper_line
                )

                if declaration:
                    name, pic_type, size_text = declaration.groups()
                    size = int(size_text)

                    if size < 1 or size > 1000:
                        self.error(
                            line_number,
                            "PIC size must be between 1 and 1000"
                        )

                    if name in self.symbol_table:
                        self.error(
                            line_number,
                            f"Duplicate declaration '{name}'"
                        )

                    self.symbol_table[name] = {
                        "type": pic_type,
                        "size": size
                    }

                    initial_value = (
                        "0" if pic_type == "9" else '""'
                    )

                    self.python_code.append(
                        f"{name.lower()} = {initial_value}"
                    )
                    continue

                if upper_line.endswith("SECTION."):
                    continue

                self.error(
                    line_number,
                    "Invalid data declaration"
                )

            # Executable statements must be in PROCEDURE DIVISION
            if self.current_section != "PROCEDURE":
                self.error(
                    line_number,
                    "Statement found outside PROCEDURE DIVISION"
                )

            # MOVE statement
            move = re.fullmatch(
                r"MOVE\s+(.+?)\s+TO\s+([A-Z][A-Z0-9-]*)\.",
                upper_line
            )

            if move:
                value, target = move.groups()

                target = self.validate_variable(
                    target,
                    line_number
                )

                target_info = self.symbol_table[target]

                if target_info["type"] == "9":
                    if not re.fullmatch(r"-?\d+", value):
                        value_name = self.validate_variable(
                            value,
                            line_number
                        )

                        if self.symbol_table[value_name]["type"] != "9":
                            self.error(
                                line_number,
                                "Cannot MOVE text into a numeric variable"
                            )

                        value = value_name.lower()

                    else:
                        if len(value.lstrip("-")) > target_info["size"]:
                            self.error(
                                line_number,
                                f"Value exceeds PIC size for '{target}'"
                            )

                else:
                    if value.startswith('"') and value.endswith('"'):
                        value = repr(value[1:-1])

                    else:
                        value_name = self.validate_variable(
                            value,
                            line_number
                        )

                        if self.symbol_table[value_name]["type"] != "X":
                            self.error(
                                line_number,
                                "Cannot MOVE a number into a text variable"
                            )

                        value = value_name.lower()

                self.python_code.append(
                    f"{target.lower()} = "
                    f"{value.lower() if value.isidentifier() else value}"
                )
                continue

            # ADD statement
            add = re.fullmatch(
                r"ADD\s+([A-Z][A-Z0-9-]*)\s+TO\s+"
                r"([A-Z][A-Z0-9-]*)\s+GIVING\s+"
                r"([A-Z][A-Z0-9-]*)\.",
                upper_line
            )

            if add:
                first, second, target = add.groups()

                self.validate_numeric_variables(
                    (first, second, target),
                    line_number,
                    "ADD"
                )

                self.python_code.append(
                    f"{target.lower()} = "
                    f"{first.lower()} + {second.lower()}"
                )
                continue

            # SUBTRACT statement
            # Example: SUBTRACT NUM1 FROM NUM2.
            subtract = re.fullmatch(
                r"SUBTRACT\s+([A-Z][A-Z0-9-]*)\s+"
                r"FROM\s+([A-Z][A-Z0-9-]*)\.",
                upper_line
            )

            if subtract:
                first, target = subtract.groups()

                self.validate_numeric_variables(
                    (first, target),
                    line_number,
                    "SUBTRACT"
                )

                self.python_code.append(
                    f"{target.lower()} = "
                    f"{target.lower()} - {first.lower()}"
                )
                continue

            # MULTIPLY statement
            # Example: MULTIPLY NUM1 BY NUM2.
            multiply = re.fullmatch(
                r"MULTIPLY\s+([A-Z][A-Z0-9-]*)\s+"
                r"BY\s+([A-Z][A-Z0-9-]*)\.",
                upper_line
            )

            if multiply:
                first, target = multiply.groups()

                self.validate_numeric_variables(
                    (first, target),
                    line_number,
                    "MULTIPLY"
                )

                self.python_code.append(
                    f"{target.lower()} = "
                    f"{target.lower()} * {first.lower()}"
                )
                continue

            # DIVIDE statement
            # Example: DIVIDE NUM1 INTO NUM2.
            divide = re.fullmatch(
                r"DIVIDE\s+([A-Z][A-Z0-9-]*)\s+"
                r"INTO\s+([A-Z][A-Z0-9-]*)\.",
                upper_line
            )

            if divide:
                first, target = divide.groups()

                self.validate_numeric_variables(
                    (first, target),
                    line_number,
                    "DIVIDE"
                )

                # Check for division by zero when the divisor
                # is already known to be zero at compile time.
                if first == target:
                    self.error(
                        line_number,
                        "Division by zero: divisor and target are the same variable"
                    )

                self.python_code.append(
                    f"if {first.lower()} == 0:"
                )
                self.python_code.append(
                    "    raise ZeroDivisionError('Division by zero')"
                )
                self.python_code.append(
                    f"{target.lower()} = "
                    f"{target.lower()} // {first.lower()}"
                )
                continue

            # DISPLAY statement
            display = re.fullmatch(
                r'DISPLAY\s+"([^"]*)"\s*'
                r'([A-Z][A-Z0-9-]*)?\.',
                line,
                re.IGNORECASE
            )

            if display:
                text, variable = display.groups()

                if variable:
                    variable = self.validate_variable(
                        variable,
                        line_number
                    )

                    self.python_code.append(
                        f"print({text!r} + str({variable.lower()}))"
                    )

                else:
                    self.python_code.append(
                        f"print({text!r})"
                    )

                continue

            self.error(
                line_number,
                f"Unsupported or invalid statement: {line}"
            )

        # Required divisions
        required = {
            "IDENTIFICATION",
            "DATA",
            "PROCEDURE"
        }

        missing = required - self.divisions

        if missing:
            raise ValueError(
                "Missing required division(s): "
                + ", ".join(sorted(missing))
            )

        # STOP RUN validation
        if not self.stopped:
            raise ValueError(
                "Program must end with STOP RUN."
            )

        # Write generated Python code
        Path(output_path).write_text(
            "\n".join(self.python_code) + "\n",
            encoding="utf-8"
        )

        print(
            f"Compilation successful: {input_path} -> {output_path}"
        )
        print(
            f"Variables declared: {len(self.symbol_table)}"
        )


def main():
    input_path = (
        sys.argv[1]
        if len(sys.argv) > 1
        else "examples/input.cbl"
    )

    output_path = (
        sys.argv[2]
        if len(sys.argv) > 2
        else "output.py"
    )

    try:
        compiler = MiniCobolCompiler()
        compiler.compile(input_path, output_path)

    except (
        ValueError,
        FileNotFoundError,
        OSError
    ) as error:
        print(
            f"Compilation error: {error}",
            file=sys.stderr
        )
        sys.exit(1)


if __name__ == "__main__":
    main()
